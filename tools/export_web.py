"""Export the stockyard sim to web/yard_data.js for the browser view (web/stockyard.html).

    py tools/export_web.py

Pure Python (no Blender): runs the wet plant and yard sims with the scripted fault and
writes one JS file (window.YARD = {...}) so the page also opens straight from disk.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from demo import config  # noqa: E402
from demo.sim import stockyard, wetplant  # noqa: E402
from demo.sim.parcel import blend  # noqa: E402
from demo.viz.colors import metric_value  # noqa: E402

METRICS = ["Fe", "SiO2", "Al2O3", "P", "LOI", "moisture", "size"]


def vals(p):
    out = {m: round(metric_value(p, m), 4) for m in METRICS}
    out["fault"] = round(p.q.get("fault_frac", 0.0), 4)
    return out


def main():
    recs = wetplant.run()
    yard = stockyard.run_yard(recs)
    pile = yard.pile
    cells = []
    for (k, j), ps in sorted(pile.cells.items()):
        c = blend(ps, "cell", 0.0)
        pieces = sorted([round(p.stamps.get("laid", 0.0), 3), round(p.dry_t, 3),
                         round(min(p.contrib), 2) if p.contrib else None] for p in ps)
        cells.append({"k": k, "j": j, "t": round(c.dry_t, 3), "v": vals(c), "pieces": pieces})
    rate = config.STOCKPILE["reclaim_tph"] / 60.0
    reclaimed = [{"m": round(m, 3), "j": j, "end": round(m + p.dry_t / rate, 3), "t": round(p.dry_t, 3),
                  "v": vals(p)} for m, j, p in yard.reclaimed]
    wagons = [{"i": w.index, "m": round(w.minute, 3), "flag": w.flagged, "slices": w.slices,
               "t": round(w.parcel.dry_t, 2), "fault_t": round(w.fault_t, 2), "v": vals(w.parcel),
               "trace": [[round(m, 2), round(t, 2), bad] for m, t, bad in w.trace(recs)]} for w in yard.wagons]
    records = [{"m": r.minute, "t": round(r.product.dry_t, 3), "v": vals(r.product),
                "cond": list(r.conditions)} for r in recs]
    var = yard.variability(recs)
    data = {
        "meta": {
            "slices": pile.slices, "layers": pile.layers, "benches": config.BWR_GEOM["benches"],
            "pass_min": config.STOCKPILE["pass_min"], "reclaim_start": config.STOCKPILE["reclaim_start_min"],
            "reclaim_tph": config.STOCKPILE["reclaim_tph"], "sim_minutes": config.SIM_MINUTES,
            "end_min": config.TIMELINE_END_MIN, "length_m": config.YARD_GEOM["length"],
            "parcel_t": config.SOURCE["parcel_t"], "payload_t": config.TRAIN["payload_t"],
            "fault_schedule": config.FAULT_SCHEDULE, "targets": config.TARGETS, "ramp": config.RAMP,
            "metrics": {m: list(config.METRICS[m]) for m in METRICS}, "hero": config.CYCLONE["hero"],
            "variability_al2o3": {k: round(v, 4) for k, v in var.items()},
        },
        "cells": cells, "reclaimed": reclaimed, "wagons": wagons, "records": records,
    }
    out = os.path.join(ROOT, "web", "yard_data.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/export_web.py from the PlantSim yard sim. Do not edit.\n")
        f.write("window.YARD = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {out}: {len(cells)} cells, {len(reclaimed)} cuts, {len(wagons)} wagons, "
          f"{os.path.getsize(out) / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
